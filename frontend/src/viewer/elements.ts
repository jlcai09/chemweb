export const COVALENT_RADII: Record<string, number> = Object.fromEntries(
  NUMBER_SYMBOLS.map((symbol, index) => [symbol, COVALENT_RADII_BY_NUMBER[index]])
    .filter((entry): entry is [string, number] => typeof entry[1] === 'number')
)

export function elementFromNumber(number?: number | null): string | null {
  if (!number) return null
  return NUMBER_SYMBOLS[number] ?? 'X'
}

export function elementColor(symbol: string): string {
  return ELEMENT_COLORS[symbol] ?? '#8b99a6'
}

export function covalentRadius(symbol: string): number {
  return COVALENT_RADII[symbol] ?? DEFAULT_COVALENT_RADIUS
}
